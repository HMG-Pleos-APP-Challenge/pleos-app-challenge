import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve,basename} from 'node:path';
import {fileURLToPath} from 'node:url';
import {parseArgs} from 'node:util';
import assert from 'node:assert/strict';

const root=new URL('../../',import.meta.url);
const hash=s=>createHash('sha256').update(s).digest('hex');
function once(sql,from,to) {assert.equal(sql.split(from).length,2,`Source drift: ${from.slice(0,60)}`);return sql.replace(from,to);}
function body(sql) {
  const start=sql.indexOf('\nbegin;');assert.ok(start>=0);
  return sql.slice(start+1).replace(/^begin;\n/m,'').replace(/^commit;\s*$/m,'').trim();
}

/** Reviewed closed-schema migration, no seed, activation, Cron, fixture clock or reset. */
export async function buildReleaseSql() {
  const parts={},hashes={};
  for(const name of ['ledger','proof','gateway','settlement','intake']) {
    const source=(await readFile(new URL(`supabase/conquest/${name}-prototype.sql`,root),'utf8')).replaceAll('\r\n','\n');
    hashes[name]=hash(source);parts[name]=body(source);
  }
  for(const name of ['ledger','proof']) {
    parts[name]=parts[name].replaceAll('p_test_admitted_ms','p_admitted_ms');
    parts[name]=once(parts[name],'p_admitted_ms bigint default null','p_admitted_ms bigint');
  }
  parts.ledger=once(parts.ledger,'(p_admitted_ms is not null and p_admitted_ms<0)','(p_admitted_ms is null or p_admitted_ms<0)');
  parts.ledger=once(parts.ledger,'coalesce(p_admitted_ms,floor(extract(epoch from clock_timestamp())*1000)::bigint)','p_admitted_ms');
  parts.ledger=parts.ledger.replace('  -- Read wall clock AFTER the scope lock. Override is for isolated boundary tests only.\n  -- A future client gateway must never expose this test argument.',
    '  -- Admission time comes only from the private gateway after acquiring the world lock.');
  const split=parts.proof.indexOf('create function conquest_internal.submit_proof(');assert.ok(split>0);
  let proofTail=parts.proof.slice(split);
  proofTail=once(proofTail,'if p_samples is null','if p_admitted_ms is null or p_admitted_ms<0 or p_samples is null');
  proofTail=once(proofTail,'coalesce(p_admitted_ms,floor(extract(epoch from clock_timestamp())*1000)::bigint)','p_admitted_ms');
  parts.proof=parts.proof.slice(0,split)+proofTail;
  parts.gateway=parts.gateway.replaceAll('public.conquest_submit_v1','conquest_internal.submit_checked');
  parts.gateway=once(parts.gateway,'grant execute on function conquest_internal.submit_checked(text,text,jsonb) to authenticated;','');
  parts.settlement=once(parts.settlement,'p_partition text,p_test_now_ms bigint default null,p_max_noons integer default 7',
    'p_partition text,p_max_noons integer default 7');
  parts.settlement=once(parts.settlement,'coalesce(p_test_now_ms,conquest_internal.admission_now_ms())','conquest_internal.admission_now_ms()');
  parts.settlement=once(parts.settlement,'settle_due(text,bigint,integer)','settle_due(text,integer)');
  parts.settlement=parts.settlement.replace(/^-- p_test_now_ms.*\n/m,'');
  parts.intake=once(parts.intake,'alter function public.conquest_submit_v1(text,text,jsonb) set schema conquest_internal;','');
  parts.intake=parts.intake.replaceAll('conquest_internal.conquest_submit_v1','conquest_internal.submit_checked');
  parts.intake=parts.intake.replace('-- Retain the exact verified gateway implementation behind a private boundary, without copying its body.',
    '-- The verified gateway was created private from the start; publish only the intake wrapper.');
  const preflight=`do $$ begin
    if to_regclass('auth.users') is null or to_regprocedure('auth.uid()') is null
      or to_regtype('extensions.geometry') is null then raise exception 'Auth and existing extensions PostGIS required';end if;
    if to_regclass('public.conquest_road_catalog') is null or to_regclass('public.conquest_ownership') is null
      then raise exception 'Existing shared reserved tables required';end if;
    if to_regnamespace('conquest_internal') is not null then raise exception 'Existing conquest installation needs explicit upgrade';end if;
    if exists(select 1 from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname in
      ('conquest_submit_v1','conquest_select_team_v1','conquest_membership_v1','conquest_snapshot_v1'))
      then raise exception 'Public conquest RPC collision';end if;
  end $$;`;
  const sql=`-- Additive conquest server v1. Prepared for review; no operating deployment is implied.
-- No catalog/team/start seed, scheduler, client activation or destructive rollback.
-- Generated by supabase/conquest/build-release.mjs; normalized-LF source SHA256:
${Object.entries(hashes).map(([n,h])=>`-- ${n}: ${h}`).join('\n')}
begin;
${preflight}
${Object.entries(parts).map(([n,s])=>`\n-- ${n}\n${s}`).join('\n')}
commit;
`;
  assert.ok(!/p_test_|fixture_clock|create\s+extension|cron\.schedule|insert\s+into\s+auth\.users|drop\s+(table|schema)/i.test(sql));
  assert.equal((sql.match(/^begin;$/gm)??[]).length,1);assert.equal((sql.match(/^commit;$/gm)??[]).length,1);
  return {sql,sourceHashes:hashes,sha256:hash(sql)};
}

/** Real hosted rehearsal only: same definitions under a fresh, non-exposed schema. */
export function isolateRelease(sql,schema) {
  assert.match(schema,/^conquest_release_[a-f0-9]{12}$/);
  let isolated=sql.replaceAll('conquest_internal',schema)
    .replace(/public\.(conquest_(?:submit|select_team|membership|snapshot)_v1)/g,`${schema}.$1`);
  isolated=once(isolated,"n.nspname='public' and p.proname in",`n.nspname='${schema}' and p.proname in`);
  return once(isolated,'\ncommit;',`\nrevoke all on all functions in schema ${schema} from public,anon,authenticated;\ncommit;`);
}

if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  const {values:v}=parseArgs({options:{out:{type:'string'},check:{type:'boolean'}}});
  assert.ok(v.out&&/^\d{14}_conquest_server_v1\.sql$/.test(basename(v.out)),'Use the path created by CLI migration new');
  const artifact=await buildReleaseSql();
  if(v.check) assert.equal((await readFile(v.out,'utf8')).replaceAll('\r\n','\n'),artifact.sql,'Migration differs from reviewed generator');
  else {await readFile(v.out);await writeFile(v.out,artifact.sql);}
  console.log(JSON.stringify({sha256:artifact.sha256,bytes:Buffer.byteLength(artifact.sql),checked:!!v.check}));
}
